    private void jBttnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBttnGuardarActionPerformed
        // TODO add your handling code here:
        String nombre = jTxtnombre.getText().trim();
        String apellido = jTxtapellido.getText().trim();
        Object seleccionado = jComboBox1.getSelectedItem();
        String rol = (seleccionado != null) ? seleccionado.toString() : "";
        String telefono = jTxttelefono.getText().trim();
        String documento = jTxtdocumento.getText().trim();
        String contrasena = jTxtcontrasena.getText().trim();
        String estado = "activo";

        if (nombre.isEmpty() || apellido.isEmpty() || rol.isEmpty() || telefono.isEmpty() || documento.isEmpty() || contrasena.isEmpty() || estado.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "por favor rellena todos los datos");
            return;
        }

        CarniceriaYare.guardarUsuario(nombre, apellido, rol, telefono, estado, documento, contrasena);

        jTxtnombre.setText("");
        jTxtapellido.setText("");
        jTxttelefono.setText("");
        jTxtdocumento.setText("");
        jTxtcontrasena.setText("");

        return;
    }//GEN-LAST:event_jBttnGuardarActionPerformed

